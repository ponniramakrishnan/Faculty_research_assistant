
import ollama
import json
from pathlib import Path
from docx import Document
from docx.enum.section import WD_ORIENT
from docx.shared import Inches

from pdf_reader import read_pdf

MODEL = "llama3.2"
PAPER_FOLDER = Path("papers")
REPORT_FOLDER = Path("reports")


# -----------------------------------------
# STEP 1: EXTRACT DETAILS FROM ONE PAPER
# -----------------------------------------

def extract_research_details(filename, paper_text):

    prompt = f"""
Extract research information from this academic paper.

Filename: {filename}

Paper content:
{paper_text[:18000]}

Extract the following fields:

1. paper_title
2. research_problem
3. research_method
4. algorithms
5. features_used
6. dataset
7. evaluation_metrics
8. performance_results
9. key_findings
10. research_novelty
11. limitations

Rules:
- Extract only information supported by the paper.
- Do not invent missing information.
- Distinguish evaluation metrics from numerical results.
- Extract dataset names and sizes where reported.
- Extract accuracy, precision, recall, F1-score, AUC, or other reported results.
- Report research novelty only when supported by the paper.
- If information is unavailable, use "Not reported".
- Keep each field concise.
- Return ONLY valid JSON.

JSON format:

{{
    "paper_title": "",
    "research_problem": "",
    "research_method": "",
    "algorithms": "",
    "features_used": "",
    "dataset": "",
    "evaluation_metrics": "",
    "performance_results": "",
    "key_findings": "",
    "research_novelty": "",
    "limitations": ""
}}
"""

    try:

        response = ollama.chat(
            model=MODEL,
            messages=[
                {
                    "role": "system",
                    "content": "Extract academic research information accurately. Do not invent facts."
                },
                {
                    "role": "user",
                    "content": prompt
                }
            ],
            format="json"
        )

        content = response.message.content

        if not content:
            print("Llama returned empty content.")
            return {}

        details = json.loads(content)

        if not isinstance(details, dict):
            print("Invalid JSON structure returned.")
            return {}

        return details

    except json.JSONDecodeError as error:

        print("JSON parsing failed:", error)
        return {}

    except Exception as error:

        print("Llama extraction error:", error)
        return {}


# -----------------------------------------
# STEP 2: PROCESS ALL PDF PAPERS
# -----------------------------------------

def collect_all_papers():

    pdf_files = list(PAPER_FOLDER.glob("*.pdf"))

    paper_details_list = []

    if not pdf_files:
        print("No PDF files found in papers folder.")
        return paper_details_list

    print(f"Found {len(pdf_files)} research papers.")

    for pdf_file in pdf_files:

        print(f"\nProcessing: {pdf_file.name}")

        text = read_pdf(str(pdf_file))

        if not text or not text.strip():
            print("No text extracted. Skipping paper.")
            continue

        print(f"Extracted {len(text)} characters.")
        print("Extracting research details using Llama...")

        try:

            details = extract_research_details(
                pdf_file.name,
                text
            )

            # Validate extracted details
            if not details or not isinstance(details, dict):
                print("No valid research details returned. Skipping paper.")
                continue

            # Add original filename
            details["filename"] = pdf_file.name

            paper_details_list.append(details)

            print("Extraction completed successfully.")

        except Exception as error:

            print("Could not process paper:", error)

    return paper_details_list


# -----------------------------------------
# STEP 3: CREATE WORD COMPARISON TABLE
# -----------------------------------------

def create_comparison_table(papers):

    REPORT_FOLDER.mkdir(exist_ok=True)

    document = Document()

    # Landscape orientation
    section = document.sections[0]
    section.orientation = WD_ORIENT.LANDSCAPE

    section.page_width, section.page_height = (
        section.page_height,
        section.page_width
    )

    # Page margins
    section.left_margin = Inches(0.4)
    section.right_margin = Inches(0.4)
    section.top_margin = Inches(0.5)
    section.bottom_margin = Inches(0.5)

    # Document heading
    document.add_heading(
        "Research Paper Comparison Analysis",
        level=0
    )

    document.add_paragraph(
        "Generated by Faculty Research Assistant using Llama 3.2"
    )

    document.add_paragraph(
        f"Number of papers analyzed: {len(papers)}"
    )

    # Table columns
    columns = [
        ("Paper Title", "paper_title"),
        ("Research Problem", "research_problem"),
        ("Methodology", "research_method"),
        ("Algorithms", "algorithms"),
        ("Features Used", "features_used"),
        ("Dataset", "dataset"),
        ("Evaluation Metrics", "evaluation_metrics"),
        ("Performance Results", "performance_results"),
        ("Key Findings", "key_findings"),
        ("Novelty", "research_novelty"),
        ("Limitations", "limitations")
    ]

    table = document.add_table(
        rows=1,
        cols=len(columns)
    )

    table.style = "Table Grid"

    # Create table header
    header_cells = table.rows[0].cells

    for i, (column_name, key) in enumerate(columns):
        header_cells[i].text = column_name

    # Add extracted paper details
    for paper in papers:

        row_cells = table.add_row().cells

        for i, (column_name, key) in enumerate(columns):

            value = paper.get(key, "Not reported")

            if not value:
                value = "Not reported"

            row_cells[i].text = str(value)

    # Save Word comparison report
    output_file = REPORT_FOLDER / "Research_Comparison_Table.docx"

    document.save(output_file)

    print("\nComparison table created successfully!")
    print("Saved at:", output_file.resolve())


# -----------------------------------------
# STEP 4: SAVE PAPER DATA TO JSON
# -----------------------------------------

def save_papers_to_json(papers):

    REPORT_FOLDER.mkdir(exist_ok=True)

    json_file = REPORT_FOLDER / "research_papers.json"

    try:

        with open(json_file, "w", encoding="utf-8") as file:

            json.dump(
                papers,
                file,
                indent=4,
                ensure_ascii=False
            )

        print("\nJSON data saved successfully!")
        print("Saved at:", json_file.resolve())

    except Exception as error:

        print("Error saving JSON file:", error)


# -----------------------------------------
# STEP 5: RUN THE COMPARISON AGENT
# -----------------------------------------

def run_comparison_agent():

    print("=" * 60)
    print("RESEARCH COMPARISON TABLE GENERATOR")
    print("=" * 60)

    papers = collect_all_papers()

    if not papers:

        print("\nNo papers available for comparison.")
        return

    print("\nTotal papers analyzed:", len(papers))

    print("\nCreating comparison table...")

    # Create Word report
    create_comparison_table(papers)

    # Save structured JSON data
    save_papers_to_json(papers)

    print("\n" + "=" * 60)
    print("COMPARISON AGENT COMPLETED SUCCESSFULLY")
    print("=" * 60)


# -----------------------------------------
# MAIN PROGRAM
# -----------------------------------------

if __name__ == "__main__":

    run_comparison_agent()
